/** UUID-owned disk DB only; no application/user DB, uninstall, reset or save-file access. */
class CompetitionMahjongRoomInstrumentedTest {
    private val context get() = InstrumentationRegistry.getInstrumentation().targetContext
    private val databaseName = "mcmt-room-qa-${UUID.randomUUID()}.db"
    private lateinit var database: MocsDatabase
    private val gameCode = GameType.STANDARD_MAHJONG.code
    private val adapter = CompetitionMahjongBackupAdapter()
    private val registry = GameBackupRegistry(listOf(adapter))

    @Before fun prepare() { database = openDisk() }
    @After fun cleanup() {
        database.close()
        // This exact name was generated by this test, never the production database name.
        assertTrue(context.deleteDatabase(databaseName))
    }

    @Test fun diskReopenKeepsTheWholeMatchAndOtherGameRows() = runBlocking {
        val checkpoint = freshCheckpoint()
        database.activeGameDao().upsert(ActiveGameEntity(GameType.CHINESE_CHESS.code, 0, null, 5, 1,
            byteArrayOf(7,8,9), 12))
        val tutorial = tutorial(4)
        database.tutorialProgressDao().upsert(tutorial)
        store().save(checkpoint)
        database.close(); database = openDisk()
        val loaded = store().load(2)!!
        assertEquals(checkpoint.config, loaded.config)
        assertEquals(checkpoint.ledger.results, loaded.ledger.results)
        assertArrayEquals(checkpoint.engineRecord, loaded.engineRecord)
        assertTrue(validateCompetitionMahjongMatchArchive(archive()))
        assertArrayEquals(byteArrayOf(7,8,9), database.activeGameDao().find(GameType.CHINESE_CHESS.code)!!.engineState)
        assertEquals(tutorial, database.tutorialProgressDao().find(gameCode))
        assertTrue(database.gameRecordDao().listAll().isEmpty())
        assertTrue(database.matchOutcomeDao().listAll().isEmpty())
    }

    @Test fun sqlReplacementFailureKeepsTheOldCompleteCheckpointAndCanRetry() = runBlocking {
        val old = freshCheckpoint(); val next = freshCheckpoint()
        store().save(old)
        database.openHelper.writableDatabase.execSQL(
            "CREATE TRIGGER reject_match BEFORE INSERT ON competition_mahjong_matches " +
                "BEGIN SELECT RAISE(ABORT, 'injected match save failure'); END")
        assertThrows(RuntimeException::class.java) { runBlocking { store().save(next) } }
        assertEquals(old.config, store().load(2)!!.config)
        assertArrayEquals(old.engineRecord, store().load(2)!!.engineRecord)
        database.openHelper.writableDatabase.execSQL("DROP TRIGGER reject_match")
        store().save(next)
        database.close(); database = openDisk()
        assertEquals(next.config, store().load(2)!!.config)
    }

    @Test fun wrongOwnerUnknownFormatAndCorruptBytesPreserveTheirEvidence() = runBlocking {
        store().save(freshCheckpoint())
        val original = database.competitionMahjongMatchDao().find(gameCode)!!
        assertThrows(IOException::class.java) { runBlocking { store().load(0) } }
        for (bad in listOf(original.copy(formatVersion = 2), original.copy(checkpoint = byteArrayOf(1,2,3)))) {
            database.competitionMahjongMatchDao().upsert(bad)
            assertThrows(IOException::class.java) { runBlocking { store().load(2) } }
            val retained = database.competitionMahjongMatchDao().find(gameCode)!!
            assertEquals(bad.formatVersion, retained.formatVersion)
            assertArrayEquals(bad.checkpoint, retained.checkpoint)
            assertThrows(IllegalArgumentException::class.java) { runBlocking { backup().export(90) } }
            assertArrayEquals(bad.checkpoint, database.competitionMahjongMatchDao().find(gameCode)!!.checkpoint)
        }
    }

    @Test fun mixedTutorialAndCompetitionBackupRestoresThroughActualNativeValidation() = runBlocking {
        val source = freshCheckpoint()
        store().save(source)
        database.tutorialProgressDao().upsert(tutorial(4))
        val bytes = backup().export(90)
        val target = Room.inMemoryDatabaseBuilder(context, MocsDatabase::class.java).build()
        try {
            val summary = backup(target).restore(bytes)
            assertEquals(1, summary.competitionMatchCount)
            assertEquals(0, summary.activeSessionCount)
            val loaded = RoomCompetitionMahjongMatchStore(target.competitionMahjongMatchDao()).load(2)!!
            assertEquals(source.config, loaded.config)
            assertArrayEquals(source.engineRecord, loaded.engineRecord)
            assertEquals(tutorial(4), target.tutorialProgressDao().find(gameCode))
            val restoredArchive = CompetitionMahjongMatchArchive.fromEntity(target.competitionMahjongMatchDao().find(gameCode)!!)
            assertTrue(validateCompetitionMahjongMatchArchive(restoredArchive))
            assertArrayEquals(bytes, backup(target).export(90))
        } finally { target.close() }
    }

    @Test fun invalidNativeRecordAndMismatchedTerminalLedgerAreRejectedBeforeAnyClear() = runBlocking {
        val old = freshCheckpoint()
        store().save(old)
        database.tutorialProgressDao().upsert(tutorial(4))
        val badNative = CompetitionMahjongMatchCheckpoint(old.config, CompetitionMahjongMatchLedger.empty(), 0,
            invalidNativeEnvelope(old.config.handConfig(0).viewerSeat))
        val hand = old.config.handConfig(0)
        val fakeTerminal = NativeCompetitionMahjongSession(hand.seed, hand.dealerSeat, hand.roundWind, hand.viewerSeat).use {
            it.snapshot().copy(phase = CompetitionMahjongRoundPhase.WON, winnerSeat = 0, payerSeat = 1,
                netScores = listOf(32,-16,-8,-8), winningFan = CompetitionMahjongFanView(0,true,8,8,true,emptyList()))
        }
        val badLedger = CompetitionMahjongMatchCheckpoint(old.config,
            CompetitionMahjongMatchLedger.empty().recordTerminal(old.config, 0, fakeTerminal), 0, old.engineRecord)
        for (bad in listOf(badNative, badLedger)) {
            val candidate = CompetitionMahjongMatchArchive(2, old.config.matchId, 99,
                CompetitionMahjongMatchCheckpointCodec.encode(bad))
            val bytes = LocalDataBackupCodec.encode(LocalDataSnapshot(99,
                gameExtensions = listOf(adapter.encodeArchive(candidate))), registry)
            assertThrows(IllegalArgumentException::class.java) { runBlocking { backup().restore(bytes) } }
            assertEquals(old.config, store().load(2)!!.config)
            assertEquals(tutorial(4), database.tutorialProgressDao().find(gameCode))
        }
    }

    @Test fun restoreWriteFailureRollsBackMatchAndTutorialTogether() = runBlocking {
        val old = freshCheckpoint(); val replacement = freshCheckpoint()
        store().save(old)
        database.tutorialProgressDao().upsert(tutorial(1))
        val bytes = LocalDataBackupCodec.encode(LocalDataSnapshot(99,
            gameExtensions = listOf(adapter.encodeArchive(CompetitionMahjongMatchArchive(2, replacement.config.matchId, 99,
                CompetitionMahjongMatchCheckpointCodec.encode(replacement)))),
            tutorialProgress = listOf(TutorialProgress(GameType.STANDARD_MAHJONG,1,4,true,99))), registry)
        database.openHelper.writableDatabase.execSQL(
            "CREATE TRIGGER reject_tutorial BEFORE INSERT ON tutorial_progress " +
                "BEGIN SELECT RAISE(ABORT, 'injected backup transaction failure'); END")
        assertThrows(RuntimeException::class.java) { runBlocking { backup().restore(bytes) } }
        assertEquals(old.config, store().load(2)!!.config)
        assertArrayEquals(old.engineRecord, store().load(2)!!.engineRecord)
        assertEquals(tutorial(1), database.tutorialProgressDao().find(gameCode))
    }

    @Test fun explicitlyRestoringLegacyBackupReplacesInsteadOfMergingTheNewMatchCategory() = runBlocking {
        store().save(freshCheckpoint())
        database.tutorialProgressDao().upsert(tutorial(4))
        val body = "MOCS-BACKUP|3\nCREATED|99\n"
        val checksum = MessageDigest.getInstance("SHA-256").digest(body.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it.toInt() and 0xff) }
        val summary = backup().restore((body + "SHA256|$checksum\n").toByteArray(Charsets.UTF_8))
        assertEquals(0, summary.competitionMatchCount)
        assertNull(store().load(2))
        assertNull(database.tutorialProgressDao().find(gameCode))
    }

    @Test fun missingCompetitionAdapterRejectsExportAndLegacyRestoreAndRetainsRowsAfterReopen() = runBlocking {
        val old = freshCheckpoint()
        store().save(old)
        val originalArchive = archive()
        val otherGame = ActiveGameEntity(GameType.CHINESE_CHESS.code, 0, null, 5, 1,
            byteArrayOf(7, 8, 9), 12)
        database.activeGameDao().upsert(otherGame)
        val originalTutorial = tutorial(4)
        database.tutorialProgressDao().upsert(originalTutorial)
        val originalCounts = userTableCounts()
        val unavailable = RoomLocalDataBackupRepository(database,
            ChineseChessEndgamePackParser.loadBundled(context.assets), validateEngineState = {
                error("Unavailable competition slot must be rejected before core engine admission")
            },
            gameBackups = GameBackupRegistry(emptyList()))
        val body = "MOCS-BACKUP|3\nCREATED|99\n"
        val checksum = MessageDigest.getInstance("SHA-256").digest(body.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it.toInt() and 0xff) }
        val emptyLegacyBackup = (body + "SHA256|$checksum\n").toByteArray(Charsets.UTF_8)
        // This otherwise valid old backup must not authorize clearing an unavailable game slot.
        assertThrows(IllegalArgumentException::class.java) { runBlocking { unavailable.export(99) } }
        assertEquals(originalArchive, archive())
        assertEquals(originalCounts, userTableCounts())
        assertThrows(IllegalArgumentException::class.java) { runBlocking { unavailable.restore(emptyLegacyBackup) } }
        assertEquals(originalArchive, archive())
        assertEquals(otherGame, database.activeGameDao().find(GameType.CHINESE_CHESS.code))
        assertEquals(originalTutorial, database.tutorialProgressDao().find(gameCode))
        assertEquals(originalCounts, userTableCounts())
        database.close(); database = openDisk()
        assertEquals(originalArchive, archive())
        assertEquals(old.config, store().load(2)!!.config)
        assertArrayEquals(old.engineRecord, store().load(2)!!.engineRecord)
        assertEquals(otherGame, database.activeGameDao().find(GameType.CHINESE_CHESS.code))
        assertEquals(originalTutorial, database.tutorialProgressDao().find(gameCode))
        assertEquals(originalCounts, userTableCounts())
    }

    /** All schema13 user tables, including empty categories, must retain their exact row counts. */
    private fun userTableCounts(): Map<String, Long> = listOf("active_games", "last_game_selections",
        "app_settings", "tutorial_progress", "match_outcomes", "game_records", "endgame_progress",
        "competition_mahjong_matches").associateWith { table ->
        database.openHelper.readableDatabase.query("SELECT COUNT(*) FROM $table").use { cursor ->
            check(cursor.moveToFirst())
            cursor.getLong(0)
        }
    }

    private fun openDisk() = Room.databaseBuilder(context, MocsDatabase::class.java, databaseName).build()
    private fun store() = RoomCompetitionMahjongMatchStore(database.competitionMahjongMatchDao()) { 42 }
    private suspend fun archive() = CompetitionMahjongMatchArchive.fromEntity(database.competitionMahjongMatchDao().find(gameCode)!!)
    private fun tutorial(count: Int) = TutorialProgressEntity(gameCode,1,count,count == 4,20)
    private fun backup(db: MocsDatabase = database) = RoomLocalDataBackupRepository(db,
        ChineseChessEndgamePackParser.loadBundled(context.assets), validateEngineState = { false }, gameBackups = registry)

    private fun freshCheckpoint(): CompetitionMahjongMatchCheckpoint {
        val config = CompetitionMahjongCompetitionConfig(UUID.randomUUID().toString(), 925, 2, 2)
        val hand = config.handConfig(0)
        return NativeCompetitionMahjongSession(hand.seed, hand.dealerSeat, hand.roundWind, hand.viewerSeat).use {
            CompetitionMahjongMatchCheckpoint(config, CompetitionMahjongMatchLedger.empty(), 0, it.serialize())
        }
    }

    private fun invalidNativeEnvelope(viewer: Int): ByteArray {
        val buffer = ByteBuffer.allocate(17).order(ByteOrder.LITTLE_ENDIAN)
        buffer.putInt(0x534d434d).put(1.toByte()).put(viewer.toByte()).putShort(0).putInt(1).put(0.toByte())
        buffer.putInt(CRC32().apply { update(buffer.array(), 0, 13) }.value.toInt())
        return buffer.array()
    }
}
